-- Compatible con PostgreSQL 15+ y Supabase.
-- Todos los identificadores utilizan BIGINT con identity autoincremental.

CREATE TABLE ambito_gestion (
    id_ambito_gestion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(100) NOT NULL,
    codigo            VARCHAR(10) NOT NULL,
    CONSTRAINT pk_ambito_gestion PRIMARY KEY (id_ambito_gestion),
    CONSTRAINT uq_ambito_gestion_codigo UNIQUE (codigo)
);

CREATE TABLE estacion (
    id_estacion                BIGINT,
    direccion                  VARCHAR(250) NOT NULL,
    comuna                     VARCHAR(100) NOT NULL,
    razon_social               VARCHAR(150) NOT NULL,
    jefe_zona                  VARCHAR(150),
    jefe_comercial             VARCHAR(150),
    rut_sociedad               VARCHAR(12),
    nombre_representante_legal VARCHAR(150),
    rut_representante_legal    VARCHAR(12),
    estado                     VARCHAR(30) NOT NULL DEFAULT 'No',
    CONSTRAINT pk_estacion PRIMARY KEY (id_estacion)
);

CREATE TABLE usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    rut                 VARCHAR(12) NOT NULL,
    contrasena_hash     VARCHAR(255) NOT NULL,
    nombres             VARCHAR(100) NOT NULL,
    primer_apellido     VARCHAR(80) NOT NULL,
    segundo_apellido    VARCHAR(80),
    correo              VARCHAR(254) NOT NULL,
    telefono            VARCHAR(30),
    descripcion         VARCHAR(500),
    rol                 VARCHAR(100) NOT NULL,
    organizacion        VARCHAR(150),
    flag_activo         BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_ultima_sesion TIMESTAMPTZ,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_rut UNIQUE (rut),
    CONSTRAINT uq_usuario_correo UNIQUE (correo)
);

CREATE TABLE etapa (
    id_etapa   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(200) NOT NULL,
    porcentaje SMALLINT NOT NULL,
    orden      INTEGER NOT NULL,
    CONSTRAINT pk_etapa PRIMARY KEY (id_etapa),
    CONSTRAINT ck_etapa_porcentaje CHECK (porcentaje BETWEEN 0 AND 100),
    CONSTRAINT ck_etapa_orden CHECK (orden > 0)
);

CREATE TABLE tipo_gestion (
    id_tipo_gestion   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gestion_padre  BIGINT,
    id_ambito_gestion BIGINT,
    nombre            VARCHAR(150) NOT NULL,
    nivel             INTEGER NOT NULL,
    flag_requerida    BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_tipo_gestion PRIMARY KEY (id_tipo_gestion),
    CONSTRAINT fk_tipo_gestion_padre FOREIGN KEY (id_gestion_padre)
        REFERENCES tipo_gestion (id_tipo_gestion) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_tipo_gestion_ambito FOREIGN KEY (id_ambito_gestion)
        REFERENCES ambito_gestion (id_ambito_gestion) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_tipo_gestion_nivel CHECK (nivel >= 1),
    CONSTRAINT ck_tipo_gestion_jerarquia CHECK (
        (nivel = 1 AND id_gestion_padre IS NULL AND id_ambito_gestion IS NOT NULL)
        OR
        (nivel > 1 AND id_gestion_padre IS NOT NULL AND id_ambito_gestion IS NULL)
    ),
    CONSTRAINT ck_tipo_gestion_no_autopadre CHECK (
        id_gestion_padre IS NULL OR id_gestion_padre <> id_tipo_gestion
    )
);

CREATE TABLE gestion (
    id_gestion              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_estacion             BIGINT NOT NULL,
    id_usuario_responsable  BIGINT NOT NULL,
    fecha_creacion          TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_apertura          DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_estimada_termino DATE,
    fecha_ultima_revision   DATE,
    prioridad               VARCHAR(10) NOT NULL,
    estado                  VARCHAR(30) NOT NULL,
    nombre_solicitante      VARCHAR(150) NOT NULL,
    flag_eliminado          BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_gestion PRIMARY KEY (id_gestion),
    CONSTRAINT fk_gestion_estacion FOREIGN KEY (id_estacion)
        REFERENCES estacion (id_estacion) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_gestion_usuario_responsable FOREIGN KEY (id_usuario_responsable)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_gestion_fechas CHECK (
        fecha_estimada_termino IS NULL OR fecha_estimada_termino >= fecha_apertura
    )
);

CREATE TABLE gestion_especifica (
    id_gestion_especifica BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gestion            BIGINT NOT NULL,
    id_tipo_gestion       BIGINT NOT NULL,
    responsable           BIGINT NOT NULL,
    estado                VARCHAR(30) NOT NULL DEFAULT 'Pendiente',
    url_archivo           VARCHAR(500),
    fecha_carga           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_gestion_especifica PRIMARY KEY (id_gestion_especifica),
    CONSTRAINT fk_gestion_especifica_gestion FOREIGN KEY (id_gestion)
        REFERENCES gestion (id_gestion) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_gestion_especifica_tipo FOREIGN KEY (id_tipo_gestion)
        REFERENCES tipo_gestion (id_tipo_gestion) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_gestion_especifica_responsable FOREIGN KEY (responsable)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE etapa_gestion (
    id_etapa_gestion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gestion       BIGINT NOT NULL,
    id_etapa         BIGINT NOT NULL,
    estado           VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    fecha_estimada   DATE,
    fecha_real       DATE,
    responsable      BIGINT,
    observaciones    VARCHAR(300),
    CONSTRAINT pk_etapa_gestion PRIMARY KEY (id_etapa_gestion),
    CONSTRAINT fk_etapa_gestion_gestion FOREIGN KEY (id_gestion)
        REFERENCES gestion (id_gestion) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_etapa_gestion_etapa FOREIGN KEY (id_etapa)
        REFERENCES etapa (id_etapa) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_etapa_gestion_responsable FOREIGN KEY (responsable)
        REFERENCES usuario (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT uq_etapa_gestion_gestion_etapa UNIQUE (id_gestion, id_etapa),
    CONSTRAINT ck_etapa_gestion_fechas CHECK (
        fecha_real IS NULL OR fecha_estimada IS NULL OR fecha_real >= fecha_estimada
    )
);

CREATE TABLE entrada_bitacora (
    id_entrada_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_gestion          BIGINT NOT NULL,
    id_usuario          BIGINT,
    fecha_registro      TIMESTAMPTZ NOT NULL DEFAULT now(),
    titulo              VARCHAR(80) NOT NULL,
    comentario          VARCHAR(1000) NOT NULL,
    tipo                VARCHAR(20),
    CONSTRAINT pk_entrada_bitacora PRIMARY KEY (id_entrada_bitacora),
    CONSTRAINT fk_entrada_bitacora_gestion FOREIGN KEY (id_gestion)
        REFERENCES gestion (id_gestion) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_entrada_bitacora_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX idx_tipo_gestion_padre ON tipo_gestion (id_gestion_padre);
CREATE INDEX idx_tipo_gestion_ambito ON tipo_gestion (id_ambito_gestion);
CREATE INDEX idx_gestion_estacion ON gestion (id_estacion);
CREATE INDEX idx_gestion_usuario_responsable ON gestion (id_usuario_responsable);
CREATE INDEX idx_gestion_especifica_gestion ON gestion_especifica (id_gestion);
CREATE INDEX idx_gestion_especifica_tipo ON gestion_especifica (id_tipo_gestion);
CREATE INDEX idx_gestion_especifica_responsable ON gestion_especifica (responsable);
CREATE INDEX idx_etapa_gestion_gestion ON etapa_gestion (id_gestion);
CREATE INDEX idx_etapa_gestion_etapa ON etapa_gestion (id_etapa);
CREATE INDEX idx_etapa_gestion_responsable ON etapa_gestion (responsable);
CREATE INDEX idx_entrada_bitacora_gestion ON entrada_bitacora (id_gestion);
CREATE INDEX idx_entrada_bitacora_usuario ON entrada_bitacora (id_usuario);

COMMENT ON COLUMN gestion_especifica.responsable IS
'Usuario responsable de esta gestión específica. Por defecto debe ser el responsable de gestion, salvo asignación explícita a otro usuario.';

COMMENT ON COLUMN gestion_especifica.url_archivo IS
'Archivo antecedente. Debe ser obligatorio para tipos de gestión con nivel mayor que 1; esta regla requiere validación de aplicación o trigger.';

COMMENT ON COLUMN tipo_gestion.id_gestion_padre IS
'Padre jerárquico. Es NULL únicamente para tipos de nivel 1.';

COMMENT ON COLUMN tipo_gestion.id_ambito_gestion IS
'Ámbito asociado exclusivamente a tipos de gestión de nivel 1.';
